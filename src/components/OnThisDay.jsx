export function getOnThisDay(date) {
  const mo = date.getMonth() + 1;
  const d  = date.getDate();
  return BTC_HISTORY.find(e => e.mo === mo && e.d === d) || null;
}

export function OnThisDay() {
  const T = useT();
  const entry = getOnThisDay(new Date());
  if (!entry) return null;

  return (
    <div>
      <Kicker>On This Day</Kicker>
      <div style={{ marginTop: 7 }}>
        <div style={{
          fontFamily: T.sans,
          fontSize: u(10),
          fontWeight: 600,
          letterSpacing: u(2),
          textTransform: 'uppercase',
          color: T.orange,
          marginBottom: u(4),
        }}>
          {MONTHS[entry.mo - 1]} {entry.d}, {entry.y}
        </div>
        <div style={{
          fontFamily: T.body,
          fontSize: u(13),
          lineHeight: 1.5,
          color: T.ink2,
          display: '-webkit-box',
          WebkitLineClamp: 3,
          WebkitBoxOrient: 'vertical',
          overflow: 'hidden',
        }}>
          {entry.t}
        </div>
      </div>
    </div>
  );
}

export default OnThisDay;
